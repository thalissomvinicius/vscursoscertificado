CREATE SCHEMA IF NOT EXISTS vscertificates;
REVOKE ALL ON SCHEMA vscertificates FROM PUBLIC, anon, authenticated;
SET search_path TO vscertificates;
CREATE TABLE users (id TEXT PRIMARY KEY, username TEXT NOT NULL UNIQUE, name TEXT NOT NULL, password TEXT NOT NULL, role TEXT NOT NULL CHECK(role IN ('admin','operator')), active INTEGER NOT NULL DEFAULT 1, created_at TEXT NOT NULL);
CREATE TABLE sessions (token TEXT PRIMARY KEY, user_id TEXT NOT NULL REFERENCES users(id), expires BIGINT NOT NULL);
CREATE TABLE settings (id INTEGER PRIMARY KEY CHECK(id=1), data TEXT NOT NULL);
CREATE TABLE certificates (id TEXT PRIMARY KEY, code TEXT NOT NULL UNIQUE, status TEXT NOT NULL CHECK(status IN ('draft','issued','revoked')), data TEXT NOT NULL, revision INTEGER NOT NULL DEFAULT 1, pdf BYTEA, pdf_hash TEXT, pdf_name TEXT, created_at TEXT NOT NULL, updated_at TEXT NOT NULL, issued_at TEXT, revoked_at TEXT, revoke_reason TEXT, user_id TEXT NOT NULL REFERENCES users(id));
CREATE TABLE audit (id BIGSERIAL PRIMARY KEY, at TEXT NOT NULL, user_id TEXT, actor TEXT NOT NULL, action TEXT NOT NULL, target TEXT NOT NULL, detail TEXT NOT NULL);
CREATE INDEX certificates_updated ON certificates(updated_at DESC);
CREATE INDEX sessions_expiry ON sessions(expires);
CREATE TABLE rate_limits (key TEXT PRIMARY KEY, count INTEGER NOT NULL, expires BIGINT NOT NULL);
CREATE TABLE transfers (id TEXT PRIMARY KEY, user_id TEXT NOT NULL REFERENCES users(id), metadata TEXT NOT NULL, expires BIGINT NOT NULL);
CREATE TABLE transfer_parts (transfer_id TEXT NOT NULL REFERENCES transfers(id) ON DELETE CASCADE, part INTEGER NOT NULL CHECK(part>=0), data BYTEA NOT NULL, PRIMARY KEY(transfer_id,part));
CREATE TABLE backups (id TEXT PRIMARY KEY, created_at TEXT NOT NULL, data BYTEA NOT NULL);
